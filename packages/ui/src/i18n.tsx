const DICTIONARY: Record<Lang, Record<MessageKey, string>> = { en, bg };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

/** Looks a key up (English fallback) and fills {placeholders}. */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const s = DICTIONARY[lang][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Translates a dynamic key (e.g. "tool." + capabilityId), falling back to `fallback`. */
export function translateMaybe(lang: Lang, key: string, fallback: string): string {
  return key in en ? translate(lang, key as MessageKey) : fallback;
}

export const localeOf = (lang: Lang) => (lang === "bg" ? "bg-BG" : "en-GB");

const STORAGE_KEY = "platform.lang";

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Translate;
  /** Translates a key built at runtime, with a fallback when it doesn't exist. */
  tm: (key: string, fallback: string) => string;
  /** Short date and time in the UI language. */
  when: (iso?: string | null) => string;
}

const I18nContext = createContext<I18n>({
  lang: "en",
  setLang: () => {},
  t: (k, v) => translate("en", k, v),
  tm: (k, f) => translateMaybe("en", k, f),
  when: (iso) => (iso ? new Date(iso).toLocaleString("en-GB", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }) : "—"),
});

/** UI language: the saved choice, otherwise the browser's language (Bulgarian or English). */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    let saved: string | null = null;
    try {
      saved = window.localStorage.getItem(STORAGE_KEY);
    } catch {
      /* storage blocked: use the browser language */
    }
    const initial = saved === "bg" || saved === "en" ? saved : navigator.language?.toLowerCase().startsWith("bg") ? "bg" : "en";
    setLangState(initial);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang,
      t: (k, v) => translate(lang, k, v),
      tm: (k, f) => translateMaybe(lang, k, f),
      when: (iso) => (iso ? new Date(iso).toLocaleString(localeOf(lang), { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }) : "—"),
    }),
    [lang, setLang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useT = () => useContext(I18nContext);
